#define MAXN 10000
const ll MOD = 1e9 + 7;

int vis[MAXN];
int dp[MAXN];
vector<int> coins;

int solve(int x) {
    if (x < 0) return 0;
    if (x == 0) return 1;

    if (vis[x]) return dp[x];

    ll n_ways = 0; 
    for (auto c: coins) {
        if (x - c >= 0) {
            n_ways += solve(x - c);
            n_ways %= MOD;
        } 
    }
    
    dp[x] = n_ways;
    vis[x] = true;
        
    return dp[x];
}

