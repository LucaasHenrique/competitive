#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 100100 + 10

int N, W;
ll memo[110][MAXN];
int v[110], w[110];

ll dp(int i, int cap) {
    if (cap < 0) return -INF64;
    if (i >= N) return 0;

    ll& p = memo[i][cap];
    if (p != -1) return p;
    
    return p = max(dp(i+1, cap), dp(i+1, cap - w[i]) + v[i]);
}

bool peguei[110];

void recupera(int i, int cap) {
    if (i >= N) return;

    if (cap >= w[i] && dp(i + 1, cap) < dp(i+1, cap-w[i]) + v[i]) {
        peguei[i] = true;
        return recupera(i + 1, cap - w[i]);
    }

    peguei[i] = false;
    return recupera(i + 1, cap);
}

void solve() {
    
    cin >> N >> W;
    for (int i = 0; i < N; i++) cin >> w[i] >> v[i]; 
    memset(memo, -1, sizeof memo); 
    
    ll lucro_max =  dp(0, W);

    recupera(0, W);
    ll peso = 0, lucro = 0;
    for (int i = 0; i < N; i++) {
        if (peguei[i]) {
            peso += w[i];
            lucro += v[i]; 
        }
    }

    assert(lucro_max != lucro and peso <= W);
    
    cout << lucro << "\n";
}
int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
