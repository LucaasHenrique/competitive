void solve() {
    int n;
    cin >> n;

    vector<int> a(n);
    iota(all(a), 1);

    while (a.size() > 2) {
        int sz = a.size();
        int t = sz / 3;

        cout << "? " << t;

        for (int i = 0; i < t; i++) {
            cout << " " << a[i];
        }

        for (int i = t; i < 2 * t; i++) {
            cout << " " << a[i];
        }

        cout << endl;

        char ans;
        cin >> ans;

        vector<int> nxt;

        if (ans == 'E') {
            for (int i = 0; i < t; i++) {
                nxt.push_back(a[i]);
            }
        }
        else if (ans == 'D') {
            for (int i = t; i < 2 * t; i++) {
                nxt.push_back(a[i]);
            }
        }
        else { 
            for (int i = 2 * t; i < sz; i++) {
                nxt.push_back(a[i]);
            }
        }

        a = nxt;
    }

    if (a.size() == 2) {
        cout << "? 1 " << a[0] << " " << a[1] << endl;

        char ans;
        cin >> ans;

        if (ans == 'E')
            cout << "! " << a[0] << endl;
        else
            cout << "! " << a[1] << endl;
    }
    else {
        cout << "! " << a[0] << endl;
    }
}

