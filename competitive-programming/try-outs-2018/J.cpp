void alphabet() {
    for (int i = 0; i <= 25; i++) {
        char t = 'A' + i;
        char sc = 'A' + (i+1);
        char an = 'A' + (i-1);
        cout << an << " " << t << " " << sc << "\n";
    }
}

void solve() {
    int n; cin >> n; 
    map<char, string> mp;
    mp['a'] = 'a';
    alphabet(); 
    for (int i = 2; i <= 26; i++) {
        char t = tolower('A' + (i-1));
        char sc = tolower('A' + (i-2));
        mp[t] = mp[sc] + t + mp[sc];
    }
    string s = mp['z'];
    n--;
    cout << s[n] << "\n";
}

