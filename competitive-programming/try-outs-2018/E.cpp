long long comb(int n, int k) {
    if (k > n) return 0;

    k = min(k, n - k);

    long long ans = 1;

    for (int i = 1; i <= k; i++) {
        ans = ans * (n - k + i) / i;
    }

    return ans;
}

void solve() {
    int n; cin >> n;
    
    if (n == 1) {cout << 0 << "\n"; return;}

    ll ans = 0;
    for (int i = 2; i <= n; i++) {
        ans += comb(n, i);
    }

    cout << ans << "\n";
}

