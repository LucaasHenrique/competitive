#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000

// r, d, u, l
int dx[] = {0, 1, -1, 0};
int dy[] = {1, 0, 0, -1};
int n, m;
pii start, dest;
queue<pii> q;

void bfs(int x, int y, vector<string>& g, vector<vector<int>>& vis) {
    while (!q.empty()) {
        pii p = q.front();
        q.pop();
        int x = p.f, y = p.s;

        for (int i = 0; i < 4; i++) {
            int nx = x + dx[i], ny = y + dy[i];
            if (nx < 0 || nx >= n || ny < 0 || ny >= m || vis[nx][ny] != -1 || g[nx][ny] == '#') continue;

            vis[nx][ny] = i;
            q.push({nx, ny});
        }
    }
}

void solve() {

    cin >> n >> m;

    vector<string> g(n);
    for (int i = 0; i < n; i++) cin >> g[i];
    vector<vector<int>>vis(n, vector<int>(m, -1));

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (g[i][j] == 'A') {
                start = {i, j};
                q.push({i, j});
            }
            else if (g[i][j] == 'B') {
                dest = {i, j};
            }
        }
    }

    bfs(start.f, start.s, g, vis);

    if (vis[dest.f][dest.s] == -1) {
        cout << "NO\n";
    }
    else {
        cout << "YES\n";
        string res = "", dir = "RDUL";
        int row = dest.f, col = dest.s;
        while (row != start.f || col != start.s) {
            int idx = vis[row][col];
            res += dir[idx];
            row -= dx[idx];
            col -= dy[idx];
        }

        reverse(res.begin(), res.end());
        cout << res.size() << "\n" << res << "\n";
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();

    return 0;
}
