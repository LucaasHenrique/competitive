using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 200000

const ll INF = ((ll)1 << 60);

int n, m;
vector<pair<ll, ll>> g[MAXN];
vector<pair<ll, ll>> rev[MAXN];

void dijkstra(int source, vector<ll>& dist, vector<pair<ll, ll>> g[]) {
    priority_queue<pair<ll, ll>, vector<pair<ll, ll>>, greater<pair<ll, ll>>> pq;
    
    vector<bool> processed;    
    dist.assign(n + 1, INF);
    processed.assign(n + 1, false);
    dist[source] = 0;
    pq.push({0, source});

    while (!pq.empty()) {
        ll a = pq.top().second;
        pq.pop();
        if (processed[a]) continue;
        processed[a] = true;
        for (auto u : g[a]) {
            ll b = u.first;
            ll w = u.second;

            if (dist[a] + w < dist[b]) {
                dist[b] = dist[a] + w;
                pq.push({dist[b], b});
            }
        }
    }
}

void solve() {
    cin >> n >> m;

    vector<tuple<int, int, ll>> edges;
    
    forn (i, m) {
        int a, b; 
        ll w;
        cin >> a >> b >> w;
        g[a].pb({b, w});
        rev[b].pb({a, w});
        edges.pb({a, b, w});
    }

    vector<pii> path;
    vector<ll> dist;
    vector<ll> dist2;   
    
    dijkstra(1, dist, g);
    dijkstra(n, dist2, rev);
    
    ll ans = INF64;
    for (auto [u, v, w]: edges) {
        ans = min(ans, dist[u] + (w / 2) + dist2[v]);
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
