#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 5000

const ll INF = ((ll)1 << 60);

int n, m; 
vector<tuple<int, int, ll>> g;
vector<ll> dist;
vector<int> rev[MAXN];
bool vis[MAXN];

void bellmanFord(int source) {
    dist.assign(n + 1, INF);
    dist[source] = 0;

    for (int i = 1; i <= n - 1; i++) {
        for (auto e : g) {
            int a, b;
            ll w;
            tie(a, b, w) = e;

            if (dist[a] != INF)
                dist[b] = min(dist[b], dist[a] + w);
        }
    }
}

void dfs(int n) {
    vis[n] = true;

    for (auto u: rev[n]) {
        if (vis[u]) continue;
        dfs(u);
    }
}

void solve() {
    cin >> n >> m;
    forn (i, m) {
        int a, b; 
        cin >> a >> b;
        ll w; cin >> w;

        g.pb({a, b, -w,});
        rev[b].pb(a);
    }

    bellmanFord(1);
    
    bool cycle = false;
    dfs(n);
    for (auto e: g) {
        int a, b;
        ll w;
        tie(a, b, w) = e;

        if (dist[a] != INF && dist[a] + w < dist[b] && vis[b]) {
            cout << -1 << "\n";
            return;
        }
    }
    cout << -dist[n] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
