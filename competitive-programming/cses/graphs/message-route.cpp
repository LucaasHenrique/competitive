#define pb push_back
#define MAXN 200100
    
vector<int> g[MAXN];
bool vis[MAXN];
bool reach =false;
map<int, int> pred;

void bfs(int x, int target) {
    
    vis[x] = true;
    queue<int> q;
    q.push(x);
    pred[x] = 0;

    while (!q.empty()) {
        auto t = q.front();
        q.pop();
        for (auto u: g[t]) {
            if (u == target) {reach = true; pred[u] = t;return; }
            if (!vis[u]) {
                vis[u] = true;
                pred[u] = t;
                q.push(u);
            }
        }
    }
}

void solve() {
   
    int n, m; cin >> n >> m;
    
    forn (i, m) {
        int a, b; cin >> a >> b;
        g[a].pb(b);
        g[b].pb(a);
    }

    bfs(1, n);
    
    vector<int> path;
    
    //cout << pred[n]<< "\n";
    if (!reach) {cout << "IMPOSSIBLE" << "\n"; return;}
    int p = n;
    while (p != 0) {
        path.pb(p);
        p = pred[p];
    }

    cout << path.size() << "\n";
    reverse(all(path));
    for (auto q: path) {
        cout << q << " ";
    }
    cout << "\n";
}

