#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 200100

int n, m;
vector<pair<ll, ll>> g[MAXN];
vector<ll> dist;
vector<bool> proc;

void dijkstra(ll s) {
    priority_queue<pair<ll, ll>, vector<pair<ll, ll>>, greater<pair<ll, ll>>> pq;

    dist.assign(n + 1, INF64);
    proc.assign(n + 1, false);

    dist[s] = 0;
    pq.push({0, s});

    while (!pq.empty()) {
        ll u = pq.top().s;
        pq.pop();

        if (proc[u]) continue;
        proc[u] = true;

        for (auto v: g[u]) {
            ll b = v.f;
            ll w = v.s;

            if (dist[b] > dist[u] + w) {
                dist[b] = dist[u] + w;
                pq.push({dist[b], b});
            }
        }
    }
}

void solve() {
    cin >> n >> m;

    forn (i, m) {
        ll a, b, c;
        cin >> a >> b >> c;
        g[a].pb({b, c});
    }

    dijkstra(1);
    for (ll i = 1; i <= n; i++) {
        cout << dist[i] << " ";
    }
    cout << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();

    return 0;
}
