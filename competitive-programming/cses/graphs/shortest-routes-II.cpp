#include <bits/stdc++.h>


using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 1; i <= n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 500
#define MAXM 250000

int n, m;
ll g[MAXN+2][MAXN+2];
ll dist[MAXN+2][MAXN+2];

void floyd_warshall() {
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= n; j++) {
            if (i == j) dist[i][j] = 0;
            else if (g[i][j] != INF64) dist[i][j] = g[i][j];
            else dist[i][j] = INF64;
        }
    }

    for (int k = 1; k <= n; k++) {
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n; j++) {
                if (dist[i][k] == INF64 || dist[k][j] == INF64) continue;
                dist[i][j] = min(dist[i][j], dist[i][k] + dist[k][j]);
            }
        }
    }
}

void solve() {
    cin >> n >> m;
    int k; cin >> k;

    forn (i, n) {
        forn (j, n) {
            g[i][j] = INF64;
        }
    }

    forn (i, m) {
        int a, b;
        cin >> a >> b;
        ll w; cin >> w;
        g[a][b] = min(g[a][b], w);
        g[b][a] = min(g[b][a], w);
    }

    floyd_warshall();
    while (k--) {
        int a, b; cin >> a >> b;
        cout << (dist[a][b] == INF64 ? -1 : dist[a][b]) << "\n";
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();

    return 0;
}
