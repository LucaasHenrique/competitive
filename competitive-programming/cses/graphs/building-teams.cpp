#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 200100

vector<int> g[MAXN];
bool possible, vis[MAXN];

void dfs(int x, vector<bool>& t, int p = 0) {
    vis[x] = true;
    
    for (auto u: g[x]) {
        if (u != p) {
            if (vis[u]) {
                if (t[u] == t[x]) possible = false;
            } else {
                t[u] = !t[x];
                dfs(u, t, x);
            }
        }
    }
}

void solve() {
    
    int n, m; cin >> n >> m;
    forn (i, m) {
        int a, b; cin >> a >> b;
        g[a].pb(b);
        g[b].pb(a);
    }
    
    vector<bool> team(n+1, 1);
    possible = true;
    for (int i = 1; i <= n; i++) {
        if (!vis[i]) {
            dfs(i, team);
        }
    }
    if (!possible) {cout << "IMPOSSIBLE" << "\n"; return;}
    for (int i = 1; i <= n; i++) cout << (team[i] ? 1 : 2) << " "; 
    cout << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
