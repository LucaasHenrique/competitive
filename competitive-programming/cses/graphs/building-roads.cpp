#define MAXN 200000

vector<int> g[MAXN];
bool vis[MAXN];
vector<int> r;

void dfs(int x) {
    vis[x] = true;

    for (auto u: g[x]) {
        if (!vis[u]) {
            dfs(u);
        }
    }
}

void solve() {
    
    int n, m; cin >> n >> m;
    forn (i, m) {
        int a, b; cin >> a >> b;
        g[a].pb(b);
        g[b].pb(a);
    }
   
    int  ans = 0;
    
    for (int i = 1; i <= n; i++) {
        if (!vis[i]) {
            ans++;
            dfs(i);
            r.pb(i);
        }
    }
    
    cout << ans - 1 << "\n";
    for (int i = 0; i < r.size() - 1; i++) {
        cout << r[i] << " " << r[i + 1] << "\n";
    }
}

