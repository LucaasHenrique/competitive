bool vis[1000][1000];
int dx[] = {0, 1, -1, 0};
int dy[] = {1, 0, 0, -1};
int n, m; 
void dfs(int x, int y, const vector<string>& g) {
     vis[x][y] = 1;
    
     for (int i = 0; i < 4; i++) {
         int xx = x + dx[i];
         int yy = y + dy[i];
        
         if (xx < 0 || xx >= n || yy < 0 || yy >= m)
            continue;

         if (!vis[xx][yy] and g[xx][yy] == '.') {
            dfs(xx, yy, g);
         }
     }
}

void solve() {
    cin >> n >> m;

    vector<string> g(n, string(m, ' '));

    for (int i = 0; i < n; i++) {
        cin >> g[i];
    }
    int ans = 0;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (!vis[i][j] and g[i][j] == '.') {ans++; dfs(i, j, g);} 
        }
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
