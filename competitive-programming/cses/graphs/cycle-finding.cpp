#include <bits/stdc++.h>
#include <ios>
#include <iostream>
#include <tuple>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 5000

int n, m;
vector<tuple<int, int, ll>> edges;
vector<ll> dist;
vector<int> parent;

void bellmanFord() {

    for (int i = 1; i <= n - 1; i++) {
        for (auto e : edges) {
            int a, b, w;
            tie(a, b, w) = e;

            if (dist[a] != INF64 && dist[b] > dist[a] + w) {
                dist[b] = dist[a] + w;
                parent[b] = a;
            }
        }
    }
}

void solve() {
    cin >> n >> m;

    edges.resize(m);
    dist.resize(n + 1, 0);
    parent.resize(n + 1, -1);

    forn (i, m) {
        int a, b;
        ll w;
        cin >> a >> b >> w;
        edges[i] = {a, b, w};
    }

    bellmanFord();
    ll cycle_start = -1;
    for (auto e : edges) {
        int a, b;
        ll w;
        tie(a, b, w) = e;
        if (dist[a] != INF64 && dist[b] > dist[a] + w) {
            dist[b] = dist[a] + w;
            parent[b] = a;
            cycle_start = b;
        }
    }

    if (cycle_start == -1) {
        cout << "NO\n";
        return;
    }

    for (int i = 0; i < n; i++) {
        cycle_start = parent[cycle_start];
    }

    vector<int> path;
    int cur = cycle_start;
    do {
        path.pb(cur);
        cur = parent[cur];
    } while (cur != cycle_start);

    path.pb(cycle_start);
    reverse(all(path));

    cout << "YES\n";
    for (auto e: path)
        cout << e << " ";

    cout << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();

    return 0;
}
