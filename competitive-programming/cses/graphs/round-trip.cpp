using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 200100

vector<int> g[MAXN];
bool vis[MAXN];
bool possible = false;
int parent[MAXN];
int s, e;

void dfs(int v, int p = 0) {
   vis[v] = true;
    
   if (possible) return;

   for (auto u: g[v]) {
        if (!vis[u]) {
            parent[u] = v;    
            dfs(u, v);
            if (possible) return;
        } else if (vis[u] && u != p) {
            s = u; 
            e = v;
            possible = true;
            return;
        }
   }
}

void solve() {
    
    int n, m; cin >> n >> m;
    forn (i, m) {
        int a, b; cin >> a >> b;
        g[a].pb(b);
        g[b].pb(a);
    }  
    
    
    vector<int> a;
    for (int i = 1; i <= n; i++) {
        if (!vis[i]){
            dfs(i);
            if (possible) break;
        }
    }
    if (!possible) {cout << "IMPOSSIBLE" << "\n"; return;}
    
    vector<int> path;
    int c = e;
    while (c != s) {
        path.pb(c);
        c = parent[c];
    }
    
    path.pb(s);
    reverse(all(path)); 
    
    path.pb(s);
    cout << path.size() << "\n";
    for (auto p: path) cout << p << " ";
    cout << "\n";
}

