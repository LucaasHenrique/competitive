#include <bits/stdc++.h>
#include <utility>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 200100

int n, m, k;
vector<pair<int, ll>> g[MAXN];
vector<ll> parent;
vector<int> cnt;

void dijkstra(int source) {
    priority_queue<pair<ll, int>, vector<pair<ll, int>>, greater<pair<ll, int>>> pq;

    cnt.assign(n + 1, 0);

    pq.push({0, source});

    while (!pq.empty()) {
        auto [d, a] = pq.top();
        pq.pop();

        if (cnt[a] == k) continue;
        cnt[a]++;

        if (a == n) {
            parent.pb(d);
            if (parent.size() == k) return;
        }

        for (auto u : g[a]) {
            int b = u.first;
            ll w = u.second;
            pq.push({d + w, b});
        }
    }
}

void solve() {
    cin >> n >> m;
    cin >> k;

    forn (i, m) {
        int a, b;
        ll w;
        cin >> a >> b >> w;
        g[a].pb({b, w});
    }

    dijkstra(1);
    for (auto e: parent) cout << e << " ";
    cout << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();

    return 0;
}
