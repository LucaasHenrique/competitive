int c = 0;
int n = 8;

bool column[100];
char diag1[200];
char diag2[200];
vector<string> grid(8);

void search(int y) {
    
    if (y == n) {
        c++;
        for (int i = 0; i < 8; i++) {
            for (int j = 0; j < 8; j++) {
                cout << grid[i][j] << "";
            }
            cout << "\n";
        }
        cout << "\n";
        return;
    } 
    for (int x = 0; x < n; x++) {
        if (column[x] || grid[y][x] == '*' || grid[y][x] == 'd' || diag1[x+y] == 'd' || diag2[x-y+n-1] == 'd') continue;
        grid[y][x] = diag1[x+y] = diag2[x-y+n-1] = 'd'; column[x] = 1;
        search(y+1);
        grid[y][x] = diag1[x+y] = diag2[x-y+n-1] = '.'; column[x] = 0;
    }

}

void solve() {
    
    for (int i = 0; i < 8; i++) {
        getline(cin, grid[i]);
    }

    search(0);
    cout << c << "\n";
}

