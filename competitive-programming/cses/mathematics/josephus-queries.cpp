ll solve(ll n, ll k) {
    if (n == 1) return 1;
    
    if (k <= (n+1)/2){
        if (2 * k > n) return (2 * k) % n;
        return 2 * k;
    }

    ll ans = solve(n/2, k - (n+1)/2);

    if (n&1) return 2 * ans +1;
    else return 2 * ans - 1;
}

