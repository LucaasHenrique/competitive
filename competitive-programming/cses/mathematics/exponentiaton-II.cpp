const ll mod = 1e9 + 7;

ll expRapida(ll base, ll exp, ll mod){
  ll res = 1;
  while(exp>0){
    if(exp&1LL) 
      res = (res*1LL*base)%mod;
    base = (base*1LL*base)%mod;
    exp = exp>>1;
  }
  return res;
}

void solve() {
    int n; cin >> n;

    while (n--) {
        ll a, b, c; cin >> a >> b >> c;

        ll res = expRapida(b, c, mod);
        
        cout << expRapida(a, res, mod) << "\n";
    }
}

