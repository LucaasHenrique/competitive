#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000000

const ll MOD = 1e9+7;

vector<int> numb = {1, 2, 3, 4, 5, 6};
bool vis[MAXN+4];
ll dp[MAXN+4];

ll solve(int x) {
    if (x < 0) return 0;
    if (x == 0) return 1;
    
    if (vis[x]) return dp[x];
    ll ways = 0;
    for (auto e: numb) {
        if (x - e >= 0) ways += solve(x - e);
    }

    ways %= MOD;
    dp[x] = ways;
    vis[x] = 1;
    
    return dp[x];
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n; cin >> n;
    cout << solve(n) << "\n";
    return 0;
}
