void solve() {
    string s, m; cin >> s >> m;
    
    int n = s.size();
    int sm = m.size();

    int dp[n+1][sm+1];

    for (int i = 0; i <= n; i++) {
        dp[i][0] = i;
    }

    for (int j = 0; j <= sm; j++) {
        dp[0][j] = j;
    }

    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= sm; j++) {
            if (s[i - 1] == m[j - 1]) {
                dp[i][j] = dp[i - 1][j - 1];
            } else {

                int insert = dp[i][j - 1] + 1;
                int rem =  dp[i - 1][j] + 1;
                int replace = dp[i - 1][j - 1] + 1;

                dp[i][j] = min({insert, rem, replace});
            }
        }
    }

    cout << dp[n][sm] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
