void solve() {
    int n; cin >> n;
    vector<int> w(n);

    int sum = 0;
    forn (i, n) {cin >> w[i]; sum += w[i];}

    
    bool dp[n+1][sum+1];
    memset(dp, 0, sizeof dp);
    // dp[n][w] -> o valor w pode ser formado usando n elementos??  
    dp[0][0] = 1;
    for (int k = 1; k <= n; k++) {
        for (int s = 0; s <= sum; s++) {
            if (s - w[k-1] >= 0) dp[k][s] |= dp[k-1][s - w[k-1]];
            dp[k][s] |= dp[k-1][s];
        }
    }
    
    set<int> s;
        for (int j = 1; j <= sum; j++) {
            if (dp[n][j]) s.insert(j); 
        }
    
    cout << s.size() << "\n";
    for (auto t: s) {
        cout << t << " ";
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
