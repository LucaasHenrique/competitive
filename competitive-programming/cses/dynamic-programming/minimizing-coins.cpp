#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000000

int dp[MAXN+4];
vector<int> numb;

int solve(int x) {
    
    if (x < 0) return INF32;
    if (x == 0) return 0;

    if (dp[x] != -1) return dp[x];
    int best = INF32;
    for (auto c: numb) {
        if (x - c >= 0) best = min(best, solve(x - c) + 1); 
    }

    dp[x] = best;
    return dp[x];
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, x; cin >> n >> x;
    memset(dp, -1, sizeof dp);

    forn (i, n) {
        int a; cin >> a;
        numb.pb(a);
    }
    
    int ans = solve(x);
    cout << (ans == INF32 ? -1 : ans) << "\n";

    return 0;
}

