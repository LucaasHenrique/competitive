// n = 27
// min(s(27 - 7), s(27 - 2));
// s(20) => min(s(20 - 2), s(20 - 0));
// s(18) => min(s(20))
// s(N) => min(s(N - Ni), s(N, Ni+1)) { 1 if N == 0 && 0 if N < 0
//
// min(s(27 - 7), s(27 - 2));
// s(20) => min(s(20 - 2), s(20 - 0)) + 1
// s(18) => min(s(18 - 1), s(18 - 8)) + 1
// s(10) => min(s(10 - 1), s(10 - 0)) + 1
// s(9) => min(s(9-9)) + 1
// s(0) => 1

int dp[MAXN+4];
bool vis[MAXN];

int solve(int n) {
    //if (n < 0) return 0;
    if (n == 0) return 0;
    if (dp[n] != -1) return dp[n];

    dp[n] = INF32;
    int t = n;
    while (t > 0) {
        int d = t % 10;
        if (d) dp[n] = min(dp[n], solve(n - d) + 1);
        t /= 10;
    }

    return dp[n];
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    
    int n; cin >> n;
    memset(dp, -1, sizeof dp);
    
    cout << solve(n) << "\n";
    return 0;
}
