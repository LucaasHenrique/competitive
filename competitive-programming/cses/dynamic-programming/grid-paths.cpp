#include <vector>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000

vector<string> g(MAXN);
ll dp[MAXN+4][MAXN+4];
const ll MOD = 1e9 + 7;
int n;

ll solve(int y, int x) {
    for (int i = 1; i < n; i++) {
    for (int j = 1; j < n; j++) {
        if (g[i][j] == '*') {
            dp[i][j] = 0;
            continue;
        }

        dp[i][j] = (dp[i-1][j] + dp[i][j-1]) % MOD;
    }
}

    return dp[y-1][x-1];
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    
    cin >> n;
    forn (i, n) {
        cin >> g[i]; 
    }
    memset(dp, 0, sizeof(dp));
    for (int i = 0; i < n; i++) {
        if (g[i][0] == '*') break;
        dp[i][0] = 1;
    }
    
    
    for (int i = 0; i < n; i++) {
        if (g[0][i] == '*') break;
        dp[0][i] = 1;
    }
    
    cout << solve(n, n) << "\n";

    return 0;
}
