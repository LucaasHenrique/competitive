#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000000

const ll MOD = 1e9 + 7;
ll dp[MAXN+4];
vector<int> coins;

ll solve(int x) {
    dp[0] = 1;
    
    for (int i = 1; i <= x; i++) {
        dp[i] = 0;
        for (auto c: coins) {
            if (i - c >= 0) dp[i] = (dp[i] + dp[i - c]) % MOD;
        }
    }

    return dp[x];
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n, x; cin >> n >> x; 
    forn (i, n) {
        int a; cin >> a;
        coins.pb(a);
    }

    cout << solve(x) << "\n";
    return 0;
}
