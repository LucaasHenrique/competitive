#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

struct Project {
    int s, e, v;
};

bool comp (Project p, Project e) {
    return p.e < e.e;
}

void solve() {
    int n; cin >> n;

    vector<Project> p(n);
    forn (i, n) {
        cin >> p[i].s >> p[i].e >> p[i].v;
    }

    sort(all(p), comp);
    
    vector<int> ends;
    for (auto &x: p) {
        ends.pb(x.e);
    }

    ll dp[n+1];
    memset(dp, 0, sizeof dp);
    
    for (int i = 1; i <= n; i++) {
        int j = lower_bound(all(ends), p[i - 1].s) - ends.begin();
        dp[i] = max(dp[i - 1], dp[j] + p[i - 1].v);
    }

    cout << dp[n] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    return 0;
}
