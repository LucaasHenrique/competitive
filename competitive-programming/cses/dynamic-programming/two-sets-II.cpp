const ll MOD = 1e9 + 7;

void solve() {
    ll n; cin >> n;

    ll s = n * (n + 1) / 2;
    if (s&1) {cout << 0 << "\n"; return;}
    

    ll target = s / 2 - n;
    // fixamos o N em algum dos conjuntos, assim, evitamos que aconteca repetição de subconjunto como: [2, 4 , 7] e [7, 4, 2];
    // sem isso teriamos que dividir o resultaado final por 2, dp[target] / 2, porem como sempre tiramos o modulo do resultado seria mais complexo

    if (target < 0) {cout << 0 << "\n"; return;}
    ll dp[target+1];
    memset(dp, 0, sizeof dp);
    dp[0] = 1;

    for (ll i = 1; i < n; i++) {
        for (ll j = target; j >= i; j--) {
            dp[j] = (dp[j] + dp[j - i]) % MOD;
        }
    }

    cout << dp[target] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
