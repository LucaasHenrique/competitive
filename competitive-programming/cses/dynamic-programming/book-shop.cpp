using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000

void solve() {
    
    int n, x; cin >> n >> x;

    ll dp[x+1];

    vector<int> books(n);
    vector<int> pages(n);
        
    for (int i = 0; i < n; i++) {
        cin >> books[i]; 
    }
    
    for (int i = 0; i < n; i++) {
        cin >> pages[i]; 
    }

    memset(dp, 0, sizeof dp);
    
    for (int i = 0; i < n; i++) {
        for (int p = x; p >= books[i]; p--) {
            dp[p] = max(dp[p], dp[p - books[i]] + pages[i]); 
        }
    }
    
    cout << dp[x] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
        
    return 0;
}
