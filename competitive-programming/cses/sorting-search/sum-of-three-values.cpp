#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

void solve() {  
    int n; cin >> n;
    ll x; cin >> x;
    vector<pair<ll, ll>> a;

    for (int i = 1; i <= n; i++) {
        int b; cin >> b;
        a.pb({b, i});
    }

    sort(a.begin(), a.end());
    for (int i = 0; i < n; i++) {
        int l = 0; int r = n - 1;
        
        while (l != r) {
            int k;
            k = x - a.at(i).f;
            int sum = (a.at(l).f + a.at(r).f); 
            if (l != i && r != i && sum == k) {
                cout << a.at(i).s << " " << a.at(l).s << " " << a.at(r).s << "\n";
                return;
            } else if (sum < k) {
                l++;
            } else {
                r--;
            }
        }
    }
    
    cout << "IMPOSSIBLE" << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
