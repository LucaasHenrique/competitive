#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100
#define len(x) int(x.size())

void solve() {
    int n; cin >> n;
    vector<tuple<ll, ll, ll>> a;

    forn (i, n) {
        ll aa, b; cin >> aa >> b;
        a.pb({aa, b, i});
    }

    sort(a.begin(), a.end());

    auto [st, et, idx] = a[0];
    vector<int> rooms(n);
    multiset<pair<int, int>> e_r;

    rooms[idx] = 1;
    e_r.emplace(et, 1);

    for (int i = 1; i< n; i++) {
        auto [st, et, idx] = a[i];
        
        auto [smaller, rid] = *begin(e_r);
        if (smaller < st) {
            e_r.erase(e_r.begin());
            rooms[idx] = rid;
            e_r.emplace(et, rid);
        } else {
            rooms[idx] = len(e_r) + 1;
            e_r.emplace(et, rooms[idx]);
        }
    }

    cout << *max_element(rooms.begin(), rooms.end()) << "\n";
    for (auto r: rooms) cout << r << " ";
    cout << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    return 0;
}
