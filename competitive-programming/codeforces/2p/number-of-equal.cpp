#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 100100

void solve() {
    int n, m; cin >> n >> m;

    ll a[n], b[m];
    forn (i, n) {
        cin >> a[i];
    }

    forn (i, m) {
        cin >> b[i];
    }
    
    map<ll, bool> vis;
    map<ll, ll> ans;
    int i = 0, j = 0;
    
    while (j < m && i < n) {
        if (vis[b[j]]) {
            j++; 
            continue;
        }

        if (a[i] < b[j]) {
            i++;
        }
        else if (a[i] == b[j]) {
            ans[b[j]]++;
            i++;
        } else if (a[i] > b[j]) {
            vis[b[j]] = 1;
            j++;
        } 
    }

    ll sum = 0;
    for (int i = 0; i < m; i++) {
        sum += ans[b[i]];
    }
    cout << sum << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
