#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

int n;
vector<ll> t_p, t_t, r_t;
// t z y
bool valid(ll t, int m) {
    // ciclo para cada assitente seria
    // tempo de ciclo = t * z * y;
    // balões por ciclo = z;
    // numero de ciclo completo = T / tempo de ciclo
    // tempo restante = T MOD tempo de ciclo
    // numero de balões = numero de ciclo completos * z + min(z, rem / t); 
    ll tot = 0;
    for (int i = 0; i < n; i++) {
        ll cycle = t_p[i] * t_t[i] + r_t[i];
        ll n_cycles = t / cycle;
        ll trem = t % cycle;
        tot += n_cycles * t_t[i] + min(t_t[i], trem / t_p[i]);
    }

    return tot >= m;
}

ll count_b(ll t, int m, int i) {
    ll cycle = t_p[i] * t_t[i] + r_t[i];
    ll n_cycles = t / cycle;
    ll trem = t % cycle;
    return n_cycles * t_t[i] + min(t_t[i], trem / t_p[i]);
}

void solve() {
    int m; cin >> m >> n;

    t_p.resize(n);
    t_t.resize(n);
    r_t.resize(n);
    forn (i, n) {
        cin >> t_p[i] >> t_t[i] >> r_t[i];
    }

    ll l = 0, r = 1e9;
    ll ans = r;
    while (l <= r) {
        ll mid = l + (r - l) / 2;
    
        if (valid(mid, m)) {
            ans = mid;
            r = mid - 1;
        } else {
            l = mid + 1;
        }
    }

    cout << ans << "\n";
    ll rem_m = m;

    for (int i = 0; i < n; i++) {
        ll ci = count_b(ans, rem_m, i);
        ll take = min(rem_m, ci);

        cout << take << (i + 1 == n ? "" : " ");
        rem_m -= take;
    }

    cout << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
