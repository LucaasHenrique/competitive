void solve() {
    
    double c; cin >> c;

    double l = 0, r = 1e10;
    double ans = r;

    for (int i = 0; i <=200; i++) {
        double mid = l + (r - l) / 2;

        if ((mid * mid) + sqrt(mid) >= c) {
            ans = mid;
            r = mid;
        } else {
            l = mid;
        }
    }

    cout <<fixed <<  setprecision(15) << ans << "\n";
}

