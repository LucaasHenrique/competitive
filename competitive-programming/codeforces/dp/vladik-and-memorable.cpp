void solve() {
    int n; cin >> n;

    vector<int> a(n+1);
    const int m = 5000;
    
    vector<int> first(m+1, n+1);
    vector<int> last(m+1);

    for (int i = 1; i<= n; i++) {
        cin >> a[i];

        first[a[i]] = min(first[a[i]], i);
        last[a[i]] = i;
    }

    int dp[n+1];
    memset(dp, 0, sizeof dp);

    for (int r = 1; r <= n; r++) {
        dp[r] = dp[r-1];
        vector<bool> used(m+1, 0);

        int mfirst = n + 1, mlast = 0, cur = 0;

        for (int l = r; l >= 1; l--) {
            
            int x = a[l];

            if (!used[x])  {
                used[x] = 1;
                cur ^= x;

                mfirst = min(mfirst, first[x]);
                mlast = max(mlast, last[x]);
            }

            if (mfirst >= l && mlast <= r) {
                dp[r] = max(dp[r], dp[l-1] + cur);
            }
        }
    }

    cout << dp[n] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
