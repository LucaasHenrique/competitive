void solve() {
    int n, m, c0, d0; cin >> n >> m >> c0 >> d0;

    int a[m+1], b[m+1], c[m+1], d[m+1];

    for (int i = 1; i <= m; i++) cin >> a[i] >> b[i] >> c[i] >> d[i];
    
    int dp[m+1][n+1];
    memset(dp, 0, sizeof dp);
    
    int k = 1;
    // make all buns without stuffing
    for (int j = 1; j <= n; j++) {
        k = 1;
        while (j - c0 * k >= 0) {
            dp[0][j] = k * d0; k++; 
        }
    }   
    
    // knapsack 
    for (int i = 1; i <= m; i++) {
        for (int j = 1; j <= n; j++) {
            dp[i][j] = dp[i-1][j];
            
            k = 1;
            while ((j - c[i] * k) >= 0 && (a[i] - b[i] * k) >= 0) {
                dp[i][j] = max(dp[i][j], dp[i-1][j - c[i] * k] + d[i] * k);
                k++;
            }
        }
    }

    cout << dp[m][n] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
