void solve() {
    
    int n, m; cin >> n >> m;

    vector<deque<int>> v;
    for (int i = 1; i <= n; i++) {
        int a; cin >> a;
        for (int j = 1; j <= a; j++) {
            int q; cin >> q;
            v[i].push_back(q);
        }
    }

    int dp[m+1][n+1];
    memset(dp, 0, sizeof dp);

    for (int i = 1; i <= m; i++) {
        for (int j = 1; j <= n; j++) {
            if (v[j].front() > dp[i-1][j-1]) {
                dp[i][j] += dp[i-1][j-1];
                v[j].pop_front();
            } else if (v[j].back() > dp[i-1][j-1]) {
                dp[i][j] += dp[i-1][j-1];
                v[j].pop_back();
            } else {
                dp[i][j] += dp[i-1][j-1];
            }
        }
    }
    
    cout << dp[m][n] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
