const int MOD = 1e8;
int dp[101][101][2][11];

void solve() {
    int n1, n2, k1, k2; cin >> n1 >> n2 >> k1 >> k2;
    
    dp[1][0][0][1] = 1;
    dp[0][1][1][1] = 1;

    for (int f = 0; f <= n1; f++) {
        for (int h = 0; h <= n2; h++) {
            for (int c = 1; c <= 10; c++) {
                
                if (dp[f][h][0][c] != 0) {
                    
                    if (f < n1 && c < k1) {
                        dp[f+1][h][0][c + 1] += dp[f][h][0][c];
                        dp[f+1][h][0][c+1] %= MOD;
                    }  

                    if (h < n2) {
                        dp[f][h+1][1][1] += dp[f][h][0][c];
                        dp[f][h+1][1][1] %= MOD;
                    }
                }

                if (dp[f][h][1][c] != 0) {
                    if (h < n2 && c < k2) {
                        dp[f][h+1][1][c+1] += dp[f][h][1][c];
                        dp[f][h+1][1][c+1] %= MOD;
                    }

                    if (f < n1) {
                        dp[f+1][h][0][1] += dp[f][h][1][c];
                        dp[f+1][h][0][1] %= MOD;
                    }
                }
            }
        } 
    }
    
    int ans = 0;
    for (int c = 1; c <= k1; c++) {
        ans += dp[n1][n2][0][c];
        ans %= MOD;
    }
    
    for (int c = 1; c <= k2; c++) {
        ans += dp[n1][n2][1][c];
        ans %= MOD;
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
