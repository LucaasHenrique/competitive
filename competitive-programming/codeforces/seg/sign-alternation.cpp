#define MAXN 300100

namespace seg {
    int seg[4*MAXN];
    int n;
    int *v;

    int build(ll p = 1, ll l = 0, ll r = n - 1) {
        if (l == r) return seg[p] = v[l];

        ll m  = (l + r) / 2;
        return seg[p] = build(2 * p, l, m) + build(2 * p + 1, m + 1, r);
    }

    void build(int n2, int *v2) {
        n = n2; v = v2;
        build();
    }

    int query(ll a, ll b, ll p = 1, ll l = 0, ll r = n - 1) {
        if (b < l || r < a) return 0;
        
        if (a <= l && r <= b) return seg[p];

        ll m = (l + r) / 2;

        return query(a, b, 2 * p, l, m) + query(a, b, 2 * p + 1, m + 1, r);
    }

    int update(int pos, ll x, ll p = 1, ll L = 0, ll R = n - 1) {
        if (L==R) return seg[p] = x;

        ll m = (L + R) / 2;

        if (pos <= m) 
            update(pos, x, 2 * p, L, m);
        else 
            update(pos, x, 2 * p + 1, m + 1, R);

        return seg[p] = seg[2*p] + seg[2*p+1];
    }
}

void solve() {
    int n; cin >> n;
    int a[n];
    forn (i, n) {
        int l; cin >> l;
        if (i&1) a[i] = -l;
        else a[i] = l;
    }
    
    int m; cin >> m;
    
    seg::build(n, a);

    while (m--) {
        int t; cin >> t;

        if (t == 0) {
            int i, j; cin >> i >> j;
            i--;
            if (i&1) j = -j;
            a[i] = j;
            seg::update(i, j);
        } else {
            int l, r; cin >> l >> r;
            l--;r--; 
            int ans = seg::query(l, r);

            if (l&1) ans = -ans;

            cout << ans << "\n";
        }
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
