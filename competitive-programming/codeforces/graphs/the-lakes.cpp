int n, m; 
int dx[] = {1, -1, 0, 0}; 
int dy[] = {0, 0, -1, 1};
int volume = 0;

void dfs(int x, int y, vector<vector<int>>& g) {
    volume += g[x][y];
    g[x][y] = 0;
    for (int i = 0; i < 4; i++) {
        int nx = x + dx[i];
        int ny = y + dy[i];

        if ((nx < 0 || nx >= n) || (ny < 0 || ny >= m)) continue;
        
        if (g[nx][ny] > 0) {
            dfs(nx, ny, g);
        }
    }   
}

void solve() {
    
    cin >> n >> m;
    
    vector<vector<int>> g(n, vector<int>(m));

    for (int i = 0; i < n; i++) 
        for (int j = 0; j < m; j++) 
            cin >> g[i][j];
    
    int ans = 0;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            
            if (g[i][j] > 0) {
                volume = 0; 
                dfs(i, j, g);
                ans = max(ans, volume);
            }
        }
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--) solve();
    
    return 0;
}
