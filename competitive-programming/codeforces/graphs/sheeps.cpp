int dx[] = {1, -1, 0, 0}; 
int dy[] = {0, 0, -1, 1};
int r, c;
int ww = 0;

void dfs(vector<string>& a) {
    for (int i = 0; i < r; i++) {
        for (int j = 0; j < c; j++) {
            
            for (int k = 0; k < 4; k++) {
                int nx = i + dx[k];
                int ny = j + dy[k];
                
                if ((nx < 0 || nx >= r) || (ny < 0 || ny >= c)) continue;
                if (a[i][j] == 'S' && a[nx][ny] == 'W') {ww = 1; return;}
                else if (a[i][j] == 'S' && a[nx][ny] == '.') a[nx][ny] = 'D';
            }
        }
    }
}

void solve() {
     cin >> r >> c;
    vector<string> a(r);

    for (int i = 0; i < r; i++) {
        cin >> a[i];
    } 
    
    bool w = 0;
    for (int i = 0; i < r; i++) {
        for (int j = 0; j < c; j++) {
            if (a[i][j] == 'W') {w = 1; break;}
        }
    }
    
    if (w) dfs(a);
    if (ww) {cout << "No" << "\n"; return;}
    cout << "Yes" << "\n";
    for (int i = 0; i < r; i++) {
        for (int j = 0; j < c; j++) {
            cout << a[i][j] << "";
        }
        cout << "\n";
    }
}
