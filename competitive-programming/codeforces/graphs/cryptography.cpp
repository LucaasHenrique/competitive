using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 126

string s, t; 
int g[MAXN+2][MAXN+2];
int dist[MAXN+2][MAXN+2];

void floyd_warshall() {
    for (int i = 33; i <= 126; i++) {
        for (int j = 33; j <= 126; j++) {
            if (i == j) dist[i][j] = 0;
            else if (g[i][j] != INF32) dist[i][j] = g[i][j];
            else dist[i][j] = INF32;
        }
    }

    for (int k = 33; k <= 126; k++) {
        for (int i = 33; i <= 126; i++) {
            for (int j = 33; j <= 126; j++) {
               if (dist[i][k] == INF32 || dist[k][j] == INF32) continue;
               dist[i][j] = min(dist[i][j], dist[i][k] + dist[k][j]);
            }
        }
    }
}

void solve() {
    cin >> s >> t;
    int m; cin >> m;
    
    for (int i = 33; i <= 126; i++)
        for (int j = 33; j <= 126; j++)
            g[i][j] = INF32;

    forn (i, m) {
        char a, b; 
        int c;
        cin >> a >> b >> c;
        g[a][b] = min(g[a][b], c);
    }
    
    floyd_warshall();
    
    //for (int i = 0; i < s.size(); i++) {
    //    cout << dist[s[i]][t[i]] << " ";
    //}

    ll ans = 0;
    for (int i = 0; i < s.size(); i++) {
        if (dist[s[i]][t[i]] == INF32) {cout << -1 << "\n"; return;}
        ans += dist[s[i]][t[i]];
    }

    cout << ans << "\n"; 
}

