#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

int n;
vector<int> a;
vector<ll> dp;
bool vis[MAXN];

ll dfs(int u) {
    if (u > n) return 0;

    if (vis[u]) return dp[u];
    vis[u] = 1;

    dp[u] = a[u] + dfs(u + a[u]);

    return dp[u];
}

void solve() {
    
    cin >> n;
    a.clear(); a.resize(n + 1);
    dp.clear(); dp.resize(n+1, 0);
    memset(vis, 0, sizeof vis);

    for (int i = 1; i <= n; i++) {
        cin >> a[i];
    }
   
    ll ans = 0;
    for (int i = 1; i <= n; i++) {
        ans = max(ans, dfs(i));
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--) solve();
    
    return 0;
}
