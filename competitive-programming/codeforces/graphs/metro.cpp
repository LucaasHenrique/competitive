    forn (i, n) {
        cin >> t2[i];
    }
    
    if (t1[1] == 0) {
        cout << "NO" << "\n";
        return;
    }
    
    int stopped = 1;
    forn (i, n) {
        if (i == s && t1[i] == 1) {cout << "YES" << '\n'; return;}
        if (t1[i] == 1 and t2[i] == 1) stopped = i;
    }
    
    for (int i = stopped; i > 0; i--) {
        if (i == s && t2[i] == 1) {cout << "YES" << '\n'; return;} 
    }

