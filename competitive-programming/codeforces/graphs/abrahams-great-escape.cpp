void solve() {
    int n, k; cin >> n >> k;

    if (k == n * n - 1) {
        cout << "NO" << "\n";
        return;
    } else {
        cout << "YES" << "\n";
        char mat[n][n];
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                if (k > 0) {
                    mat[i][j] = 'U'; k--;
                } else if (i == n - 1 && j == n - 1){
                    mat[i][j] = 'L';
                } else if (i == n - 1) mat[i][j] = 'R';
                else mat[i][j] = 'D';
            }   
        }

        for (int i = 0; i < n; i++) {
            for (int j = 0; j < n; j++) {
                cout << mat[i][j];
            }   
            cout << "\n";
        } 
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--) solve();
    
    return 0;
}
