using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

int n, m, x;

vector<pair<int, int>> g[MAXN+1];
vector<bool> vis;


vector<int> dijkstra(int s, vector<int> d) {
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> pq;
    
    d.assign(n + 1, INF32);
    vis.assign(n + 1, false);
    
    d[s] = 0;
    pq.push({0, s});

    while (!pq.empty()) {
        int a = pq.top().s;
        pq.pop();
        
        if (vis[a]) continue;
        vis[a] = true;
        
        for (auto u: g[a]) {
            int b = u.first;
            int w = u.s;

            if (d[a] + w < d[b]) {
                d[b] = d[a] + w;
                pq.push({d[b], b});
            }
        }
    }

    return d;
}

void solve() {
    cin >> n >> m >> x;

    forn (i, m) {
        int u, v, w; cin >> u >> v >> w;
        g[u].pb({v, w});
        g[v].pb({u, w});
    }
    
    vector<int> dist; 
    vector<int> dn; 
    dist = dijkstra(1, dist);
    dn = dijkstra(n, dn);

    int ans =INF32;
    for (int i = 1; i <= x; i++) {
        int a; cin >> a;
        ans = min(ans, dist[a] + dn[a]); 
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
