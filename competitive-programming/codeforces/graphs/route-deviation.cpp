#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

int n, m, c, k;
vector<pair<int, int>> g[MAXN];
bool vis[MAXN];

void dijkstra(int s, vector<int>& dist) {
    priority_queue<pair<int, int>, vector<pair<int, int>>, greater<pair<int, int>>> q;
    dist[s] = 0;
    q.push({0, s});
    
    memset(vis, 0, sizeof vis);

    while (!q.empty()) {
        int a = q.top().s;
        q.pop();
    
        if (vis[a]) continue;
        vis[a] = true;

        if (a < c) {
            continue;
        }
        for (auto u: g[a]) {
            int b = u.f;
            int w = u.s;
            
            if (dist[a] + w < dist[b]) {
                dist[b] = dist[a] + w;
                q.push({dist[b], b});
            } 
        }
    }
} 

void solve() {

    while (true) {
        cin >> n >> m >> c >> k;
        if (n == 0 && m == 0 && c == 0 && k == 0) return;
        
        for (int i = 0; i < m; i++) {
            int a, b, p; cin >> a >> b >> p;
            g[a].pb({b, p});
            g[b].pb({a, p});
        }
     
        vector<int> d2; d2.assign(n + 1, INF32);

        dijkstra(k, d2);
       

        int ans = INF32;
        
        vector<int> route(c);
        route[c - 1] = 0;
        for (int i = c - 2; i >= 0; i--) {
            for (auto [v, w]: g[i]) {
                if (v == i + 1) {
                    route[i] = route[i + 1] + w;
                }
            }
        }
    
        for (int i = 0; i < c; i++) {
            ans = min(ans, d2[i] + route[i]);
        }

        cout << ans << "\n";
        for (int i = 0; i < n; i++) g[i].clear();
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
