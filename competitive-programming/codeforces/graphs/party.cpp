#define MAXN 2000

int n;
vector<int> g[MAXN+1];
int ans = 0;

void dfs(int a, int p) {
    ans = max(ans, p);
    for (auto b: g[a]) {
        dfs(b, p + 1);
    }
}

void solve() {
    cin >> n;

    for (int i = 1; i <= n; i++) {
        int p; cin >> p;
        if (p != -1) {
            g[p].pb(i);
        }
    }

    for (int i = 1; i <= n; i++) dfs(i, 1);
    cout << ans << "\n";
}

