void solve() {
    int n; cin >> n;
    int a[n+1];

    for (int i = 1; i <= n; i++) {
        cin >> a[i]; 
    }
   
    if (a[1] == 1) {
        cout << n + 1 << " ";
        for (int i = 1; i <= n; i++) cout << i << " ";
        cout << "\n";
        return;
    } 

    if (a[n] == 0) {
        for (int i = 1; i <= n; i++) cout << i << " "; 
        cout << n + 1 << " ";
        cout << "\n";
        return;
    }

    for (int i = 1; i < n; i++) {
        if (a[i] == 0 and a[i + 1] == 1) {
            for (int j = 1; j <= i; j++) cout << j << " ";
            cout << n + 1 << " ";
            for (int j = i + 1; j <= n; j++) cout << j << " ";
            
            cout << "\n";
            return;
        }
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;
    while (t--) solve();
    
    return 0;
}
