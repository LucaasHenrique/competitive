#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 2000000
const ll INF = 1e18;

int n, m;
vector<pair<int, ll>> g[MAXN];
vector<ll> dist;
vector<bool> processed;

void dijkstra(int source) {
    priority_queue<pair<ll, int>, vector<pair<ll, int>>, greater<pair<ll, int>>> pq;
    
    dist.assign(n + 1, INF);
    processed.assign(n + 1, false);

    dist[source] = 0;
    pq.push({0, source});

    while (!pq.empty()) {
        ll a = pq.top().second;
        pq.pop();
        if (processed[a]) continue;
        processed[a] = true;
        for (auto u : g[a]) {
            ll b = u.first;
            ll w = u.second;

            if (dist[a] + w < dist[b]) {
                dist[b] = dist[a] + w;
                pq.push({dist[b], b});
            }
        }
    }
}

void solve() {
   cin >> n >> m;
  
   forn (i, m) {
       int a, b;
       ll w;
       cin >> a >> b >> w;
       g[a].push_back({b, w});
       g[b].push_back({a, w});
   }

   dijkstra(1);
    
   cout << (dist[n] == INF ? -1 : dist[n]) << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
