using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(t, n) for (ll i = t; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

bool comp(pair<int, pair<ll, ll>> a, pair<int, pair<ll, ll>> b) {
    if (a.s.f != b.s.f) {
        return a.s.f > b.s.f;
    } else if (a.s.s != b.s.s) 
        return a.s.s < b.s.s;
    else return a.f < b.f;
}

void solve() {
    int n; cin >>n;

    vector<pair<int, pair<ll, ll>>> a;

    for (int i = 1; i <= n; i++) {
        ll q, p; cin >> q >> p;
        a.pb({i, {q, p}});
    }
    
    sort(a.begin(), a.end(), comp);
    
    cout << a[0].f << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
