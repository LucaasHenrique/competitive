using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 310

double dp[MAXN+1][MAXN+1][MAXN+1];  
int n;

double calc(int i, int j, int k) {
    
    if (dp[i][j][k] != -1) return dp[i][j][k];

    double s = i + j + k;
    double exp = n;
    
    if (i > 0) exp += i * calc(i - 1, j, k);
    if (j > 0) exp += j * calc(i + 1, j - 1, k);
    if (k > 0) exp += k * calc(i, j + 1, k - 1);
    
    return dp[i][j][k] = exp/s;
}

void solve() {
    cin >> n;
    
    int i = 0, j = 0, k = 0;
    forn (u, n) {
        int a; cin >> a;
        if (a == 1) i++;
        if (a==2) j++;
        if (a == 3) k++;
    }

    for (int i = 0; i <= n; i++) {
        for (int j = 0; j <= n; j++) {
            for (int k = 0; k <= n; k++) {
                dp[i][j][k] = -1;
            }
        }
    }
    dp[0][0][0] = 0;

    cout << fixed << setprecision(10) << calc(i, j, k) << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
