const ll MOD = 1e9 + 7;


int mod(int a) {
    a %= MOD;
    if (a < 0) a += MOD;
    return a;
}

int add(int a, int b) {
    a = mod(a), b = mod(b);
    return (a + b) % MOD;
}

void solve() {
    int n, k; cin >> n >> k;

    ll a[n+10];

    for (int i = 1; i <= n; i++) cin >> a[i];
    
    ll dp[n + 10][k + 10];
    memset(dp, 0, sizeof dp);
    dp[0][0] = 1;
        
    for (int i = 1; i <= n; i++) {
        vector<ll> pref(k + 10);

        for (int j = 0; j <= k; j++) {
            pref[j] = add(pref[j], dp[i-1][j]);
            if (j + a[i] + 1 <= k) pref[j + a[i] + 1] = add(pref[j + a[i] + 1], -dp[i-1][j]);
        }

        for (int j = 1; j <= k; j++) pref[j] = add(pref[j], pref[j-1]);
        for (int j = 0; j <= k; j++) dp[i][j] = pref[j];
    }

    cout << dp[n][k] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
