#define f first
#define s second
#define pb push_back
#define MAXN 300100

vector<vector<int>> adj;
vector<int> state;
vector<int> topo;

bool dfs(int u) {
    state[u] = 1;

    for (int v : adj[u]) {

        if (state[v] == 1)
            return false; 

        if (state[v] == 0) {
            if (!dfs(v))
                return false;
        }
    }

    state[u] = 2;
    topo.push_back(u);

    return true;
}

bool topological_sort(int n) {
    state.assign(n+1, 0);
    topo.clear();

    for (int u = 1; u <= n; u++) {
        if (state[u] == 0) {
            if (!dfs(u))
                return false;
        }
    }

    reverse(topo.begin(), topo.end());
    return true;
}

void solve() {
    int n, m; cin >> n >> m;
    
    adj.assign(n + 1, vector<int>());
    forn (i, m) {
        int a, b; cin >> a >> b;
        adj[a].pb(b);
    }
    
    topological_sort(n);

    vector<int> dp(n+1, 0);
    for (auto u: topo) {
        for (auto v: adj[u]) {
            dp[v] = max(dp[v], dp[u] + 1);
        }
    }

    cout << *max_element(all(dp)) << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
