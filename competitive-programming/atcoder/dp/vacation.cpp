void solve() {
    int n; cin >> n;
    vector<int> a(n), b(n), c(n);


    // dp[i][j] -> maximo de ponto no i-th dia, sendo a ativiade j a ultima escolhida.
    ll dp[n][3], happiness[n][3];
    
    forn (i, n) {
        cin >> happiness[i][0] >> happiness[i][1] >> happiness[i][2];
    }
    
    dp[0][0] = happiness[0][0];
    dp[0][1] = happiness[0][1];
    dp[0][2] = happiness[0][2];

    for (int i = 1; i < n; i++) {
        
        // i-th day, chosen A
        dp[i][0] = happiness[i][0] + max(dp[i-1][1], dp[i-1][2]);
        
        // i-th day, chosen B
        dp[i][1] = happiness[i][1] + max(dp[i-1][0], dp[i-1][2]);
        
        // i-th day chosen C
        dp[i][2] = happiness[i][2] + max(dp[i-1][0], dp[i-1][1]);
    }

    cout << max({dp[n-1][0], dp[n-1][1], dp[n-1][2]}) << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
