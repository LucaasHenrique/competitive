/* 

dp[i][j] -> melhor ganho para o jogador atual no intervalo [i, j];
se o elemento da extrmidade i foi escolhido então o proximo jogador vai conseguir a vantagem no intervalo [i + 1, j]
se foi o elemento da extremidade j, então o proximo consegue a vantagem no intervalo [i, j - 1]

*/

void solve() {
    int n; cin >> n; 
    
    ll a[n+1];
    for (int i = 1; i <= n; i++) {
        cin >> a[i];
    } 
    
    ll dp[n + 1][n + 1];
    dp[1][1] = a[1];
        
    int k = 1;
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= n; j++) {
            if (i == j) {
                dp[i][j] = a[i];
            }
        }
    } 

    for (int l = 2; l <= n; l++) {
        for (int i = 1; i + l - 1 <= n; i++) {
            
            int j = i + l - 1;

            dp[i][j] = max(a[i] - dp[i + 1][j], a[j] - dp[i][j - 1]);
        }
    }
    
    cout << dp[1][n] << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
