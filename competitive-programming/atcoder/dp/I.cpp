#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

void solve() {

    int n; cin >> n;
    double p[n];
    forn (i, n) {
        cin >> p[i];
    }

    double dp[n+1][n+1];
    
    memset(dp, 0.0, sizeof dp);
    dp[0][0] = 1.0;    
    
    for (int i = 1; i <= n; i++) {
        for (int h = 0; h <= n; h++) {
            if (h > 0) {
                dp[i][h] += dp[i-1][h-1] * p[i-1];
            }

            dp[i][h] += dp[i-1][h] * (1 - p[i-1]);
        }
    }

    double ans = 0.0;
    for (int h = n / 2 + 1; h <= n; h++) {
        ans += dp[n][h];
    }

    cout << fixed << setprecision(10) << ans << '\n';
}


int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
