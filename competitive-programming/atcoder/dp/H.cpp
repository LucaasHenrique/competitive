#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1000

const ll MOD = 1e9 + 7;

void solve() {
    int h, w; cin >> h >> w;

    vector<string> a(h);
    forn (i, h) {
        cin >> a[i];
    }

    ll dp[MAXN+1][MAXN+1];
    memset(dp, 0, sizeof dp);
    
    dp[0][0] = 1;
    for (int j = 1; j < w; j++) {
        if (a[0][j] == '#') break;
        else dp[0][j] += dp[0][j-1];
    }

    for (int i = 1; i < h; i++) {
        if (a[i][0] == '#') break;
        else dp[i][0] += dp[i-1][0];
    }

    for (int i = 1; i < h; i++) {
        for (int j = 1; j < w; j++) {
            if (a[i][j] == '#') continue; 
            if (j-1 < 0 || i - 1 < 0) continue;
            dp[i][j] += ((dp[i][j-1] + dp[i-1][j]));
            dp[i][j] %= MOD;
        }
    }

    cout << dp[h-1][w-1] % MOD << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
