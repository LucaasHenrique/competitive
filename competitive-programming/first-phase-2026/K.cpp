#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100

void solve() {
    int n; cin >> n;
    
    vector<pair<ll, ll>> c;
    forn (i, n) { 
        ll ci; cin >> ci;
        c.pb({ci, 0});
    }

    bool ok = true;
    forn (i, n) { 
        ll k; cin >> k;
        c[i].s = k;
        if (c[i].f < k) {
            ok = false;
            break;
        }
    }
    
    if (!ok) {
        cout << -1 << "\n"; return;
    }
    
    ll ans = 0;
    ll m_diff = INF64;
    forn (i, n) {
        ans += c[i].f;
        m_diff = min(m_diff, abs(c[i].f - c[i].s));
    } 

    cout << ans - m_diff << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
