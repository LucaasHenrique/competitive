#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 1010

int n, m; 
char a[MAXN][MAXN];

int n2, m2;
char b[MAXN][MAXN], c[MAXN][MAXN];

bool igual() {
    if (n2 != n ||  m2 != m) return false;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            if (a[i][j] != b[i][j]) return false;
        }
    }

    return true;
}

void virar() {
    for (int i = 0; i < n2; i++) 
        for (int j = 0; j < m2 - 1 - j; j++) 
            swap(b[i][j], b[i][m2-1-j]); 
}

void girar() {
    for (int i = 0; i < n2; i++)
        for (int j = 0; j < m2; j++) 
            c[j][n2-1-i] = b[i][j];
    
    swap(n2, m2);
    for (int i = 0; i < n2; i++)
        for (int j = 0; j < m2; j++)
            b[i][j] = c[i][j];
}

void solve() {
    
    cin >> n >> m;
    n2 = n; m2 = m;
    
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cin >> a[i][j];
            b[i][j] = a[i][j];
        }
    }

    ll ans = 0;
    for (int i =0;  i< 4; i++) {
        ans += igual();
        virar();
        ans += igual();
        virar();
        girar();
    }

    cout << ans << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
