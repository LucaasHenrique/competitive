void solve() {
    int n; cin >> n; 
    
    vector<double> a(n);
    double a_c = 0, a_v = 0;
    for (int i = 0; i < n; i++) {
        double c, v; cin >> c >> v;
        a_c += c;
        a_v += v;
        a[i] = (double)(a_c - a_v) / (a_c  + a_v);
    }

    int q; cin >> q;
    while (q--) {
        int b; cin >> b;
        b--;
        if (a[b] > 0) cout << "COMPRA" << "\n";
        if (a[b] < 0) cout << "VENDA" << "\n";
        if (a[b] == 0) cout << "NEUTRO" << "\n";
    }
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
