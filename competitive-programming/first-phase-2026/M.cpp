#include <bits/stdc++.h>

using namespace std;

#define range(it, a, b) for (ll it = a; it < b; it++)
#define forn(i, n) for (ll i = 0; i < n; i++)
#define all(x) begin(x), end(x)
#define ll long long
#define ull unsigned long long
#define pii pair<int, int>
#define pll pair<ll, ll>
#define INF64 ((ll) 1 << 60)
#define INF32 (1 << 30)
#define f first
#define s second
#define pb push_back
#define MAXN 300100
#define piii pair<ll, pair<ll, ll>>

int n, m, k;
vector<pair<ll, ll>> g[MAXN];
ll dist[MAXN][12]; // the lowest latency to arrive on the node u using K edges of micro-ondas

ll dijkstra() {
    for (int i = 1; i <= n; i++) 
        for (int j = 0; j <= k; j++) dist[i][j] = INF64;
    
    dist[1][0] = 0; 
    priority_queue<piii, vector<piii>, greater<piii>> q;
    q.push({0, {1, 0}});

    while (!q.empty()) {
        auto v = q.top().s;
        auto d= q.top().f;
        q.pop();
        if (v.f == n) return d;

        // if the distance is worse than the dist to arrive on the vertice u using k elements
        if (d > dist[v.f][v.s]) continue;

        for (auto u : g[v.f]) {
            pair<ll, ll> x;

            if (u.s < 0) {
                x = {u.f, v.s + 1};
            } else {
                x = {u.f, v.s};
            }

            ll dis = abs(u.s);

            if (x.s <= k && dist[x.f][x.s] > dis + d) {
                dist[x.f][x.s] = dis + d;
                q.push({dist[x.f][x.s], x});
            } 
        }
    }

    return -1;
}


void solve() {
    cin >> n >> m >> k;

    forn (i, m) {
        ll a, b, c, d; cin >> a >> b >> c >> d;
        g[a].pb({b, c});
        g[b].pb({a, c});

        if (d != -1) { 
            g[a].pb({b, -d});
            g[b].pb({a, -d});
        }
    }

    cout << dijkstra() << "\n";
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    //cin >> t;
    while (t--) solve();
    
    return 0;
}
