#define MAXN 30010000

int f[MAXN+1], a[MAXN+1];

void solve() {
    int n; cin >> n;
    
    f[1] = 2;
    a[2] = 1;

    for (int i = 2; i <= n; i++) {
        if (a[i] != 0) {
            f[i] = a[i] * 3;
            a[f[i]] = i;
        }
        else {
            f[i] = f[i-1] + 1;
            a[f[i]] = i; 
        }
    }

    cout << f[n] << "\n";
}

